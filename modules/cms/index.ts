/**
 * CMS module. From the .ts files in cms/ (which mirror app/), it generates:
 *
 * 1. public/admin/config.yml: the Sveltia CMS config (see ./build.ts)
 * 2. .nuxt/types/cms.d.ts: TypeScript types for everything defined in cms/,
 *    imported with `import type { QuoteBlock } from '#cms'` (see ./types.ts)
 *
 * content.config.ts also builds its Nuxt Content schemas from cms/ (./schema.ts),
 * and field values are transformed at build time (./transform.ts): Markdown is
 * parsed, and images get their dimensions.
 *
 *   cms/config.ts                        base config + sidebar order  (nuxt.config.ts)
 *   cms/app.ts                           singletons                   (app/app.vue)
 *   cms/pages/[...slug].ts               collection                   (app/pages/[...slug].vue)
 *   cms/components/Header.ts             navigation file              (app/components/Header.vue)
 *   cms/components/blocks/Quote.ts       page block                   (app/components/blocks/Quote.vue)
 *   cms/components/partials/CmsVideo.ts  shared field + component     (app/components/partials/CmsVideo.vue)
 *   cms/fields/seo.ts                    shared field                 (used by several collections)
 *
 * Each file default-exports its part using the typed helpers in ./define.ts.
 *
 * Both run whenever Nuxt starts (dev, generate, build, prepare/typecheck).
 * While `pnpm dev` is running, a valid change to cms/ restarts Nuxt so the
 * config, types and content schemas all pick it up.
 */
import { existsSync, watch, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { addTemplate, addTypeTemplate, defineNuxtModule, useLogger } from 'nuxt/kit'
import { stringify } from 'yaml'
import { SOURCE_DIR, buildCms } from './build'
import { checkEmbedComponents, generateEditorComponents, generateEmbedComponents } from './embeds'
import { transformContent } from './transform'
import { generateTypes } from './types'

const CONFIG_FILE = 'public/admin/config.yml'
const EDITOR_COMPONENTS_FILE = 'public/admin/editor-components.js'
const TYPES_FILE = 'types/cms.d.ts'

export default defineNuxtModule({
  meta: { name: 'cms' },
  setup(_options, nuxt) {
    const logger = useLogger('cms')
    const sourceDir = join(nuxt.options.rootDir, SOURCE_DIR)

    if (!existsSync(sourceDir)) {
      logger.warn(`No ${SOURCE_DIR}/ directory found; skipping CMS config and types.`)
      return
    }

    // Built once: a change to cms/ restarts Nuxt in dev anyway. Errors fail the
    // build, so a broken CMS config never gets deployed.
    const build = buildCms(sourceDir)
    const partialsDir = join(nuxt.options.srcDir, 'components/partials')
    checkEmbedComponents(build.embeds, partialsDir)

    const header = [`# GENERATED by modules/cms from ${SOURCE_DIR}/. Do not edit.`, `# Change the files in ${SOURCE_DIR}/ instead.`, '']
    writeFileSync(join(nuxt.options.rootDir, CONFIG_FILE), header.join('\n') + stringify(build.config, { lineWidth: 0 }))
    // Rich text embeds, registered in Sveltia by public/admin/index.html (./embeds.ts).
    writeFileSync(join(nuxt.options.rootDir, EDITOR_COMPONENTS_FILE), generateEditorComponents(build.embeds))
    logger.success(`Generated ${CONFIG_FILE} from ${SOURCE_DIR}/`)

    // Transform field values (Markdown, images, embeds) as Nuxt Content reads each file.
    nuxt.hook('content:file:afterParse', ({ file, content }) =>
      transformContent(build, nuxt.options.rootDir, file, content),
    )

    // The partial that renders each embed, for <CmsRichText>: #build/cms/embeds
    addTemplate({ filename: 'cms/embeds.ts', write: true, getContents: () => generateEmbedComponents(build.embeds, partialsDir) })

    // Embeds are imported lazily, so each partial loads only where it's used. A
    // partial that's also used directly in a block is already in that page's
    // code, and the bundler warns that the lazy import can't split it out. That's
    // expected and harmless, so only that warning about embeds is dropped.
    nuxt.hook('vite:extendConfig', (config) => {
      const build = ((config as { build?: Record<string, any> }).build ??= {})
      const options = (build.rolldownOptions ??= {})
      const onwarn = options.onwarn
      options.onwarn = (warning: { code?: string; message?: string }, warn: (warning: unknown) => void) => {
        if (warning.code === 'INEFFECTIVE_DYNAMIC_IMPORT' && /cms(\/|%2F)embeds/.test(warning.message ?? '')) return
        if (onwarn) onwarn(warning, warn)
        else warn(warning)
      }
    })

    // Rebuilt each time Nuxt (re)writes its templates.
    addTypeTemplate({ filename: TYPES_FILE, getContents: () => generateTypes(buildCms(sourceDir)) })

    if (nuxt.options.dev) {
      let timer: NodeJS.Timeout | undefined
      const watcher = watch(sourceDir, { recursive: true }, () => {
        clearTimeout(timer)
        timer = setTimeout(async () => {
          // Check the change first, so a half-finished edit doesn't take the dev server down.
          try {
            buildCms(sourceDir)
          } catch (error) {
            logger.error(`cms/ has an error, nothing regenerated: ${(error as Error).message}`)
            return
          }
          logger.info(`${SOURCE_DIR}/ changed, restarting to regenerate the CMS config, types and content schemas`)
          await nuxt.callHook('restart')
        }, 200)
      })
      nuxt.hook('close', () => watcher.close())
    }
  },
})
