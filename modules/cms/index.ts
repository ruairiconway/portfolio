/**
 * CMS module. From the .yml files in cms/ (which mirror app/), it generates:
 *
 * 1. public/admin/config.yml: the Sveltia CMS config (see ./build.ts)
 * 2. .nuxt/types/cms.d.ts: TypeScript types for everything defined in cms/,
 *    imported with `import type { QuoteBlock } from '#cms'` (see ./types.ts)
 *
 * content.config.ts also builds its Nuxt Content schemas from cms/ (./schema.ts),
 * and field values are transformed at build time (./transform.ts): Markdown is
 * parsed, and images get their dimensions.
 *
 *   cms/config.yml                   base config + sidebar order  (nuxt.config.ts)
 *   cms/app.yml                      singletons                   (app/app.vue)
 *   cms/pages/[...slug].yml          collection                   (app/pages/[...slug].vue)
 *   cms/components/SiteHeader.yml    navigation file              (app/components/SiteHeader.vue)
 *   cms/components/blocks/Quote.yml  page block                   (app/components/blocks/Quote.vue)
 *   cms/components/partials/CmsVideo.yml  shared field + component (app/components/partials/CmsVideo.vue)
 *   cms/fields/seo.yml               shared field                 (used by several collections)
 *
 * Both run whenever Nuxt starts (dev, generate, build, prepare/typecheck).
 * While `pnpm dev` is running, a valid change to cms/ restarts Nuxt so the
 * config, types and content schemas all pick it up.
 */
import { existsSync, watch, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { addTypeTemplate, defineNuxtModule, useLogger } from 'nuxt/kit'
import { stringify } from 'yaml'
import { SOURCE_DIR, buildCms } from './build'
import { transformContent } from './transform'
import { generateTypes } from './types'

const CONFIG_FILE = 'public/admin/config.yml'
const TYPES_FILE = 'types/cms.d.ts'

export default defineNuxtModule({
  meta: { name: 'cms' },
  setup(_options, nuxt) {
    const logger = useLogger('cms')
    const sourceDir = join(nuxt.options.rootDir, SOURCE_DIR)

    if (!existsSync(sourceDir)) {
      logger.warn(`No ${SOURCE_DIR}/ directory found; skipping CMS config and types.`)
      return
    }

    const writeConfig = () => {
      const header = [
        `# GENERATED by modules/cms from ${SOURCE_DIR}/. Do not edit.`,
        `# Change the files in ${SOURCE_DIR}/ instead.`,
        '',
      ].join('\n')
      writeFileSync(join(nuxt.options.rootDir, CONFIG_FILE), header + stringify(buildCms(sourceDir).config, { lineWidth: 0 }))
    }

    // Errors fail the build, so a broken CMS config never gets deployed.
    writeConfig()
    logger.success(`Generated ${CONFIG_FILE} from ${SOURCE_DIR}/`)

    // Transform field values (Markdown, images) as Nuxt Content reads each file.
    // The config is built once: a change to cms/ restarts Nuxt in dev anyway.
    const { config } = buildCms(sourceDir)
    nuxt.hook('content:file:afterParse', ({ file, content }) =>
      transformContent(config, nuxt.options.rootDir, file, content),
    )

    // Rebuilt each time Nuxt (re)writes its templates.
    addTypeTemplate({ filename: TYPES_FILE, getContents: () => generateTypes(buildCms(sourceDir)) })

    if (nuxt.options.dev) {
      let timer: NodeJS.Timeout | undefined
      const watcher = watch(sourceDir, { recursive: true }, () => {
        clearTimeout(timer)
        timer = setTimeout(async () => {
          // Check the change first, so a half-finished edit doesn't take the dev server down.
          try {
            buildCms(sourceDir)
          } catch (error) {
            logger.error(`cms/ has an error, nothing regenerated: ${(error as Error).message}`)
            return
          }
          logger.info(`${SOURCE_DIR}/ changed, restarting to regenerate the CMS config, types and content schemas`)
          await nuxt.callHook('restart')
        }, 200)
      })
      nuxt.hook('close', () => watcher.close())
    }
  },
})
