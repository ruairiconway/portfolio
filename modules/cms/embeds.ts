/**
 * Embeds: partials that editors can insert into rich text.
 *
 * A file in cms/components/partials/ exports `embed = defineEmbed({...})`. Its
 * id comes from the filename (CmsImage.ts -> "cms-image"), and it's rendered by
 * the partial of the same name (app/components/partials/CmsImage.vue).
 *
 * 1. In the CMS: public/admin/editor-components.js (generated here) registers
 *    each embed as a Sveltia editor component, under Insert in the rich text
 *    toolbar of any field whose `editor_components` includes it.
 * 2. In the Markdown, an embed is saved as an MDC block component. Values are
 *    HTML-escaped; anything that isn't a string is JSON, on a `:`-prefixed key:
 *      ::cms-image{image="/images/uploads/photo.webp" alt="A photo"}
 *      ::
 * 3. At build time, the Markdown is parsed (./transform.ts) and each embed's
 *    attributes become the partial's props, typed by the embed's fields: JSON is
 *    parsed and image paths become CmsImage objects with their dimensions.
 * 4. On the page, <CmsRichText> renders each embed with its partial
 *    (#build/cms/embeds, generated here).
 */
import { existsSync } from 'node:fs'
import { join } from 'node:path'
import { isObject, type CmsEmbedBuild, type Obj } from './build'

/** public/admin/editor-components.js: registers the embeds in Sveltia. */
export function generateEditorComponents(embeds: CmsEmbedBuild[]): string {
  const definitions = embeds.map(({ id, definition }) => {
    const { fields, ...options } = definition
    return { id, label: options.label ?? id, options, fields }
  })
  return `// GENERATED by modules/cms from the \`embed\` exports in cms/components/partials/.
// Do not edit; change those files instead (see modules/cms/embeds.ts).
//
// Registers each embed as a component in Sveltia's rich text editor. It's saved
// in the Markdown as an MDC block component, e.g.
//   ::cms-image{image="/images/uploads/photo.webp" alt="A photo"}
//   ::

;(() => {
const EMBEDS = ${JSON.stringify(definitions, null, 2)}

// Attribute values are HTML-escaped, including braces and backslashes, so any
// text survives the Markdown round trip. The site's Markdown parser decodes them.
const ESCAPES = { '&': '&amp;', '\\\\': '&#92;', '"': '&quot;', "'": '&#39;', '\\n': '&#10;', '{': '&#123;', '}': '&#125;' }
const encode = (text) => String(text).replace(/[&\\\\"'\\n{}]/g, (char) => ESCAPES[char])
const decode = (text) =>
  text.replace(/&(amp|quot|#\\d+);/g, (_, entity) =>
    entity === 'amp' ? '&' : entity === 'quot' ? '"' : String.fromCharCode(Number(entity.slice(1))),
  )

const isEmpty = (value) => value === undefined || value === null || value === ''

function toAttributes(data) {
  return Object.entries(data ?? {})
    .filter(([, value]) => !isEmpty(value))
    .map(([key, value]) =>
      typeof value === 'string' ? \`\${key}="\${encode(value)}"\` : \`:\${key}="\${encode(JSON.stringify(value))}"\`,
    )
    .join(' ')
}

function fromAttributes(text) {
  const data = {}
  for (const [, bound, key, value] of text.matchAll(/(:?)([A-Za-z_][\\w-]*)="([^"]*)"/g)) {
    const decoded = decode(value)
    try {
      data[key] = bound ? JSON.parse(decoded) : decoded
    } catch {
      data[key] = decoded
    }
  }
  return data
}

const escapeHtml = (text) =>
  String(text).replace(/[&<>"]/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[char])

/** The first image in the data, looking inside object fields too. */
function findImage(fields, data) {
  for (const field of fields ?? []) {
    const value = data?.[field.name]
    if (field.widget === 'image' && typeof value === 'string' && value) return value
    if (field.widget === 'object' && value) {
      const nested = findImage(field.fields, value)
      if (nested) return nested
    }
  }
}

function toPreview(embed, data) {
  const image = findImage(embed.fields, data)
  return image
    ? \`<img src="\${escapeHtml(image)}" alt="" style="max-width: 100%; height: auto">\`
    : \`<p><strong>\${escapeHtml(embed.label)}</strong></p>\`
}

for (const embed of EMBEDS) {
  window.CMS.registerEditorComponent({
    ...embed.options,
    id: embed.id,
    fields: embed.fields,
    pattern: new RegExp(\`^::\${embed.id}\\\\{([^}\\\\n]*)\\\\}\\\\n::$\`, 'm'),
    fromBlock: (match) => fromAttributes(match[1]),
    toBlock: (data) => \`::\${embed.id}{\${toAttributes(data)}}\\n::\`,
    toPreview: (data) => toPreview(embed, data),
  })
}
})()
`
}

/** Fails if an embed has no partial to render it. */
export function checkEmbedComponents(embeds: CmsEmbedBuild[], componentsDir: string): void {
  for (const { component, file } of embeds) {
    if (!existsSync(join(componentsDir, `${component}.vue`))) {
      throw new Error(`${file} exports an embed, but there's no app/components/partials/${component}.vue to render it`)
    }
  }
}

/** #build/cms/embeds: the partial that renders each embed, loaded only when used. */
export function generateEmbedComponents(embeds: CmsEmbedBuild[], componentsDir: string): string {
  const entries = embeds.map(({ id, component }) => {
    const path = join(componentsDir, `${component}.vue`)
    return `  ${JSON.stringify(id)}: defineAsyncComponent(() => import(${JSON.stringify(path)})) as AnyComponent,`
  })
  return [
    '// GENERATED by modules/cms: the partial that renders each rich text embed.',
    "import { defineAsyncComponent, type DefineComponent } from 'vue'",
    '',
    '// The shape <MDCRenderer :components> expects.',
    'type AnyComponent = DefineComponent<any, any, any>',
    '',
    'export const embedComponents: Record<string, AnyComponent> = {',
    ...entries,
    '}',
    '',
  ].join('\n')
}

type FieldTransform = (data: Obj, fields: Obj[]) => Promise<void>

/**
 * Turns the embeds in a parsed Markdown tree into their partials' props:
 * `:key` JSON is parsed, then the embed's fields are transformed like any other
 * fields (images get dimensions, Markdown is parsed). Missing string fields
 * become '', so props like `alt` are always set.
 */
export async function transformEmbeds(node: unknown, embeds: Map<string, Obj[]>, transformFields: FieldTransform): Promise<void> {
  if (!isObject(node)) return
  const fields = typeof node.tag === 'string' ? embeds.get(node.tag) : undefined
  if (fields) {
    const props: Obj = {}
    for (const [key, value] of Object.entries(isObject(node.props) ? node.props : {})) {
      if (key.startsWith(':') && typeof value === 'string') {
        try {
          props[key.slice(1)] = JSON.parse(value)
        } catch {
          props[key.slice(1)] = value
        }
      } else props[key] = value
    }
    for (const field of fields) {
      if (props[String(field.name)] === undefined && (field.widget ?? 'string') === 'string') props[String(field.name)] = ''
    }
    await transformFields(props, fields)
    node.props = props
  }
  if (Array.isArray(node.children)) {
    for (const child of node.children) await transformEmbeds(child, embeds, transformFields)
  }
}
